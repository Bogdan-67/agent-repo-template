#!/usr/bin/env python3
"""sync: generate harness-specific wrappers from the neutral sources of truth.

Sources (edit these):
  docs/agents/<role>.md        neutral role definitions (frontmatter: name, description,
                               when_to_use, read_only) — the body is the role itself
  .agents/skills/<name>/       Agent Skills (agentskills.io)

Generated (never edit by hand; each file carries a GENERATED marker):
  .claude/agents/<role>.md          Claude Code subagent
  .codex/agents/<role>.toml         Codex custom agent
  .agents/agents/<role>.md          Kimi Code CLI agent (uses ${base_prompt})
  .opencode/agents/<role>.md        OpenCode subagent
  .github/agents/<role>.agent.md    GitHub Copilot custom agent
  .claude/skills/<name> -> ../../.agents/skills/<name>   symlinks (Claude Code does not read .agents/skills)

Commands
  sync.py            write wrappers and symlinks, remove stale generated files
  sync.py --check    verify everything is in sync and valid (exit 1 on drift); use in CI and pre-commit
  sync.py lock --template-dir DIR   write .agents/template.lock from DIR/MANIFEST.json

Standard library only, Python 3.8+.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

MARK = "GENERATED by .agents/bin/sync.py from {src}; edit the source, then run: python3 .agents/bin/sync.py"
SKIP_ROLES = {"README.md", "domain.md", "cold-start-quiz.md"}
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def root_dir() -> Path:
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    return Path(out.stdout.strip() or os.getcwd()).resolve()


def frontmatter(text: str) -> tuple:
    """Minimal YAML frontmatter reader: flat 'key: value' pairs, quotes stripped."""
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end < 0:
        return {}, text
    meta = {}
    for line in text[4:end].splitlines():
        if ":" in line and not line.startswith((" ", "\t", "#")):
            k, v = line.split(":", 1)
            v = v.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                v = v[1:-1]
            meta[k.strip()] = v
    body = text[end + 4:].lstrip("\n")
    return meta, body


def yq(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # JSON strings are valid YAML double-quoted scalars


def roles(root: Path) -> list:
    out = []
    d = root / "docs" / "agents"
    for f in sorted(d.glob("*.md")) if d.is_dir() else []:
        if f.name in SKIP_ROLES:
            continue
        meta, _ = frontmatter(f.read_text(encoding="utf-8"))
        if not meta.get("name"):
            continue
        out.append({
            "name": meta["name"], "src": f.relative_to(root).as_posix(),
            "description": meta.get("description", ""),
            "when": meta.get("when_to_use", ""),
            "read_only": meta.get("read_only", "false").lower() in ("true", "yes", "1"),
        })
    return out


def pointer(r: dict) -> str:
    ro = ("\nThis role is read-only: do not create, edit or delete files; report findings instead.\n"
          if r["read_only"] else "")
    return (f"Your complete role definition is `{r['src']}`. Read it in full now and follow it. "
            f"Repository rules are in `AGENTS.md`.\n{ro}")


def render(r: dict) -> dict:
    n, src, desc, when = r["name"], r["src"], r["description"], r["when"]
    mark = MARK.format(src=src)
    full_desc = desc + (f" Use when: {when}" if when else "")
    files = {}
    tools = "\ntools: Read, Grep, Glob" if r["read_only"] else ""
    files[f".claude/agents/{n}.md"] = (
        f"---\nname: {n}\ndescription: {yq(full_desc)}{tools}\n---\n<!-- {mark} -->\n\n{pointer(r)}")
    files[f".agents/agents/{n}.md"] = (
        f"---\nname: {n}\ndescription: {yq(desc)}\n" + (f"whenToUse: {yq(when)}\n" if when else "") +
        f"---\n<!-- {mark} -->\n${{base_prompt}}\n\n# Role: {n}\n\n{pointer(r)}")
    files[f".opencode/agents/{n}.md"] = (
        f"---\ndescription: {yq(full_desc)}\nmode: subagent\n---\n<!-- {mark} -->\n\n{pointer(r)}")
    files[f".github/agents/{n}.agent.md"] = (
        f"---\nname: {n}\ndescription: {yq(full_desc)}\n---\n<!-- {mark} -->\n\n{pointer(r)}")
    instr = pointer(r).replace('"""', "'''")
    files[f".codex/agents/{n}.toml"] = (
        f"# {mark}\nname = {json.dumps(n.replace('-', '_'))}\ndescription = {json.dumps(full_desc, ensure_ascii=False)}\n"
        f'developer_instructions = """\n{instr}"""\n')
    return files


def generated_dirs() -> list:
    return [".claude/agents", ".agents/agents", ".opencode/agents", ".github/agents", ".codex/agents"]


def is_generated(p: Path) -> bool:
    try:
        return "GENERATED by .agents/bin/sync.py" in p.read_text(encoding="utf-8")[:600]
    except (OSError, UnicodeDecodeError):
        return False


def skills(root: Path) -> list:
    d = root / ".agents" / "skills"
    return sorted(p for p in d.iterdir() if (p / "SKILL.md").exists()) if d.is_dir() else []


def validate(root: Path) -> list:
    errs = []
    for s in skills(root):
        meta, body = frontmatter((s / "SKILL.md").read_text(encoding="utf-8"))
        name, desc = meta.get("name", ""), meta.get("description", "")
        if name != s.name:
            errs.append(f"skill {s.name}: frontmatter name '{name}' must equal the directory name")
        if not NAME_RE.match(name) or len(name) > 64:
            errs.append(f"skill {s.name}: name must be lowercase letters, digits, single hyphens, <=64 chars")
        if not 1 <= len(desc) <= 1024:
            errs.append(f"skill {s.name}: description must be 1..1024 characters")
        if "<" in desc or ">" in desc:
            errs.append(f"skill {s.name}: no angle brackets in description")
        if len(body.splitlines()) > 500:
            errs.append(f"skill {s.name}: SKILL.md body over 500 lines; move detail to references/")
    for r in roles(root):
        if not NAME_RE.match(r["name"]):
            errs.append(f"role {r['src']}: name must be kebab-case")
        if not r["description"]:
            errs.append(f"role {r['src']}: description is required")
    agents = root / "AGENTS.md"
    if agents.exists() and agents.stat().st_size > 32768:
        errs.append("AGENTS.md exceeds 32 KiB (Codex truncates the AGENTS.md chain at this size)")
    claude = root / "CLAUDE.md"
    if claude.exists() and "@AGENTS.md" not in claude.read_text(encoding="utf-8"):
        errs.append("CLAUDE.md must import AGENTS.md with a line '@AGENTS.md'")
    return errs


def plan(root: Path) -> tuple:
    want = {}
    for r in roles(root):
        want.update(render(r))
    stale = []
    for d in generated_dirs():
        for f in (root / d).glob("*") if (root / d).is_dir() else []:
            rel = f.relative_to(root).as_posix()
            if f.is_file() and rel not in want and is_generated(f):
                stale.append(rel)
    links = {f".claude/skills/{s.name}": f"../../.agents/skills/{s.name}" for s in skills(root)}
    return want, stale, links


def sync(root: Path, check: bool) -> int:
    errs = validate(root)
    want, stale, links = plan(root)
    drift = []
    for rel, content in want.items():
        p = root / rel
        cur = p.read_text(encoding="utf-8") if p.exists() else None
        if cur == content:
            continue
        if cur is not None and not is_generated(p):
            errs.append(f"{rel} exists and is not generated; move its content to the neutral source "
                        f"and delete it, or rename the role")
            continue
        drift.append(f"write {rel}")
        if not check:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")
    for rel in stale:
        drift.append(f"remove stale {rel}")
        if not check:
            (root / rel).unlink()
    for rel, target in links.items():
        p = root / rel
        if p.is_symlink() and os.readlink(p) == target:
            continue
        if p.exists() and not p.is_symlink():
            continue  # a real directory: the user keeps a Claude-specific copy on purpose
        drift.append(f"link {rel} -> {target}")
        if not check:
            p.parent.mkdir(parents=True, exist_ok=True)
            if p.is_symlink():
                p.unlink()
            os.symlink(target, p)
    for e in errs:
        print("ERROR:", e)
    if check:
        for d in drift:
            print("DRIFT:", d)
        if drift:
            print("Run: python3 .agents/bin/sync.py")
        ok = not drift and not errs
        print("sync --check:", "OK" if ok else "FAILED")
        return 0 if ok else 1
    for d in drift:
        print(d)
    print("sync: done" + (" with errors" if errs else ""))
    return 1 if errs else 0


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def lock(root: Path, template_dir: Path) -> int:
    manifest = json.loads((template_dir / "MANIFEST.json").read_text(encoding="utf-8"))
    files = {}
    for rel, owner in manifest["files"].items():
        p = root / rel
        if owner == "template" and p.is_file():
            files[rel] = sha(p)
    data = {"template": manifest.get("name", "agent-repo-template"), "version": manifest["version"],
            "source": manifest.get("source", ""), "template_owned_sha256": files}
    out = root / ".agents" / "template.lock"
    out.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(root)} ({len(files)} template-owned files, version {manifest['version']})")
    return 0


def main() -> int:
    args = sys.argv[1:]
    root = root_dir()
    if args and args[0] == "lock":
        if "--template-dir" not in args:
            print("usage: sync.py lock --template-dir DIR")
            return 1
        return lock(root, Path(args[args.index("--template-dir") + 1]).resolve())
    return sync(root, check="--check" in args)


if __name__ == "__main__":
    sys.exit(main())
