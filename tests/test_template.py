"""Integration tests for agent-repo-template. Run: python3 -m unittest discover -s tests -v"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

T = Path(__file__).resolve().parents[1]
PY = sys.executable


def sh(cwd, *args, check=True):
    r = subprocess.run(args, cwd=cwd, capture_output=True, text=True, stdin=subprocess.DEVNULL)
    if check and r.returncode != 0:
        raise AssertionError(f"{args} failed:\n{r.stdout}\n{r.stderr}")
    return r


class InstalledProject(unittest.TestCase):
    def setUp(self):
        self.p = Path(tempfile.mkdtemp(prefix="art_"))
        sh(self.p, "git", "init", "-q")
        sh(self.p, "git", "config", "user.email", "t@t")
        sh(self.p, "git", "config", "user.name", "t")
        shutil.copytree(T / "payload", self.p, dirs_exist_ok=True, symlinks=True)

    def tearDown(self):
        shutil.rmtree(self.p, ignore_errors=True)

    def test_sync_generates_wrappers_and_links(self):
        sh(self.p, PY, ".agents/bin/sync.py")
        for rel in [".claude/agents/reviewer.md", ".codex/agents/reviewer.toml", ".agents/agents/reviewer.md",
                    ".opencode/agents/reviewer.md", ".github/agents/reviewer.agent.md"]:
            self.assertTrue((self.p / rel).exists(), rel)
        self.assertIn("${base_prompt}", (self.p / ".agents/agents/reviewer.md").read_text())
        self.assertIn("tools: Read, Grep, Glob", (self.p / ".claude/agents/reviewer.md").read_text())
        link = self.p / ".claude/skills/session-close"
        self.assertTrue(link.is_symlink() and (link / "SKILL.md").exists())
        sh(self.p, PY, ".agents/bin/sync.py", "--check")
        if sys.version_info >= (3, 11):
            import tomllib
            data = tomllib.loads((self.p / ".codex/agents/reviewer.toml").read_text())
            self.assertEqual(set(data), {"name", "description", "developer_instructions"})

    def test_check_detects_drift_and_bad_skill(self):
        sh(self.p, PY, ".agents/bin/sync.py")
        (self.p / ".claude/agents/reviewer.md").write_text("GENERATED by .agents/bin/sync.py tampered")
        self.assertEqual(sh(self.p, PY, ".agents/bin/sync.py", "--check", check=False).returncode, 1)
        sh(self.p, PY, ".agents/bin/sync.py")
        bad = self.p / ".agents/skills/Bad_Skill"
        bad.mkdir()
        (bad / "SKILL.md").write_text("---\nname: other\ndescription: x\n---\nbody\n")
        r = sh(self.p, PY, ".agents/bin/sync.py", "--check", check=False)
        self.assertEqual(r.returncode, 1)
        self.assertIn("must equal the directory name", r.stdout)

    def test_stale_wrapper_removed(self):
        sh(self.p, PY, ".agents/bin/sync.py")
        (self.p / "docs/agents/docs-keeper.md").unlink()
        sh(self.p, PY, ".agents/bin/sync.py")
        self.assertFalse((self.p / ".codex/agents/docs-keeper.toml").exists())

    def test_guard_self_test(self):
        r = sh(self.p, PY, ".agents/hooks/docs_guard.py", "self-test", check=False)
        self.assertEqual(r.returncode, 0, r.stdout)

    def test_lock(self):
        sh(self.p, PY, ".agents/bin/sync.py", "lock", "--template-dir", str(T))
        lock = json.loads((self.p / ".agents/template.lock").read_text())
        self.assertEqual(lock["version"], (T / "VERSION").read_text().strip())
        self.assertIn(".agents/hooks/docs_guard.py", lock["template_owned_sha256"])

    def test_hook_configs_are_valid_json(self):
        for rel in [".claude/settings.json", ".codex/hooks.json", ".gemini/settings.json",
                    ".github/hooks/docs-guard.json", ".agents/guard.json"]:
            json.loads((self.p / rel).read_text())

    def test_claude_hook_command_runs(self):
        sh(self.p, "git", "add", "-A")
        sh(self.p, "git", "commit", "-qm", "init", "--no-verify")
        cmd = json.loads((self.p / ".claude/settings.json").read_text())["hooks"]["SessionStart"][0]["hooks"][0]["command"]
        r = subprocess.run(["sh", "-c", cmd], cwd=self.p, capture_output=True, text=True,
                           input=json.dumps({"session_id": "x", "cwd": str(self.p)}))
        self.assertIn("additionalContext", r.stdout)

    def test_commit_msg_hook_rejects_ai_coauthor(self):
        sh(self.p, PY, ".agents/bin/sync.py")
        sh(self.p, "git", "config", "core.hooksPath", ".githooks")
        sh(self.p, "git", "add", "-A")
        r = sh(self.p, "git", "commit", "-qm", "init\n\nCo-Authored-By: Claude Sonnet 4.6 <noreply@anthropic.com>", check=False)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("AI attribution", r.stdout + r.stderr)
        r = sh(self.p, "git", "commit", "-qm", "init\n\nCo-authored-by: Jane <jane@example.com>", check=False)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_manifest_covers_payload(self):
        m = json.loads((T / "MANIFEST.json").read_text())
        files = {p.relative_to(T / "payload").as_posix() for p in (T / "payload").rglob("*") if p.is_file()}
        self.assertEqual(files, set(m["files"]))

    def test_agents_md_limits(self):
        text = (T / "payload/AGENTS.md").read_text()
        self.assertLessEqual(len(text.splitlines()), 150)
        self.assertLess(len(text.encode()), 32768)

    @unittest.skipUnless(shutil.which("bun"), "bun not installed")
    def test_opencode_plugin_v1_and_v2(self):
        sh(self.p, "git", "add", "-A")
        sh(self.p, "git", "commit", "-qm", "init", "--no-verify")
        harness = self.p / "harness.ts"
        harness.write_text(r'''
import plugin from "./.opencode/plugins/docs-guard.ts"
const dir = process.cwd(); const out: string[] = []
// V1
const v1 = await plugin.server({ client: { session: { prompt: async (a: any) => { out.push("v1:" + a.body.noReply + ":" + a.body.parts[0].text.slice(0, 12)) } } }, directory: dir, worktree: dir })
await v1.event({ event: { type: "session.created", properties: { info: { id: "s1" } } } })
await Bun.sleep(1100); await Bun.write("src.py", "x=1\n")
await v1.event({ event: { type: "session.idle", properties: { sessionID: "s1" } } })
await Bun.sleep(100)
// V2
const queue: any[] = [{ type: "session.created", data: { info: { id: "s2" } } }]
const ctx = {
  location: { directory: dir },
  event: { subscribe: () => ({ async *[Symbol.asyncIterator]() { while (queue.length || !done) { if (queue.length) yield queue.shift(); else await Bun.sleep(20) } } }) },
  session: { instructions: { entry: { put: async (a: any) => { out.push("v2ctx:" + a.key) } } }, prompt: async (a: any) => { out.push("v2prompt:" + a.text.slice(0, 13)) } },
}
let done = false
const stop = plugin.setup(ctx)
await Bun.sleep(300); await Bun.sleep(1100); await Bun.write("src2.py", "y=1\n")
queue.push({ type: "session.idle", data: { sessionID: "s2" } }); await Bun.sleep(1500); done = true; stop()
console.log(out.join("\n"))
''')
        r = sh(self.p, "bun", "run", "harness.ts")
        self.assertIn("v1:true:[docs_guard]", r.stdout)
        self.assertIn("v1:false:Documentati", r.stdout)
        self.assertIn("v2ctx:docs-guard", r.stdout)
        self.assertIn("v2prompt:Documentation", r.stdout)


if __name__ == "__main__":
    unittest.main()
